#!/usr/bin/env python3
"""Generates src/Ops/Fused.luau: handlers for hot adjacent instruction pairs.

Luau has no first-class operators, so each operator combination is written out. Every maker returns a chained
or a returning handler; both instructions' effects are kept (the first result is still stored), except in the
"Dead" branch variants, which Analysis selects only when the tested value is never read again.

Usage: gen_fused.py > src/Ops/Fused.luau
"""

OPS = {"ADD": "+", "SUB": "-", "MUL": "*", "DIV": "/"}

out = []
emit = out.append


def maker(name, params, body, doc):
    """Emits one maker with a chained and a returning variant of `body` (a list of statement lines)."""
    emit(f"-- {doc}")
    emit(f"{name} = function({', '.join(params)}, Next: Handler, Chain: boolean): Handler")
    for chained in (True, False):
        indent = "\t\t" if chained else "\t"
        if chained:
            emit("\tif Chain then")
        emit(f"{indent}return function(S)")
        for line in body:
            emit(f"{indent}\t{line}")
        emit(f"{indent}\treturn {'Next(S)' if chained else 'Next'}")
        emit(f"{indent}end")
        if chained:
            emit("\tend")
    emit("end")
    emit("")


emit("""--!optimize 2
--!strict

-- GENERATED by tools/gen_fused.py; edit the generator, not this file.
--
-- Handlers for hot adjacent instruction pairs (field loads feeding arithmetic, arithmetic feeding stores and
-- other arithmetic). One fused handler replaces two handler calls; the first instruction's result is still
-- written, so the pair behaves exactly like its two instructions in order.
-- @param Next Handler – successor, or a loop token in returning mode
-- @param Chain boolean – whether to call Next directly

local Types = require("../Types")

type Handler = Types.Handler

local Fused = {}

-- GETTABLEKS/GETTABLEN pairs
Fused.GetGet = nil :: any
Fused.GetSet = nil :: any
Fused.SetGet = nil :: any
-- GETUPVAL (by value) feeding a table read
Fused.UpGetK = nil :: any
Fused.UpGet = nil :: any
-- [op][side]: field load feeding the left ("L") or right ("R") operand of a register-register operator
Fused.GetArith = {} :: { [string]: { [string]: any } }
-- [op][side]: register-key table load feeding a register-register operator
Fused.GetRArith = {} :: { [string]: { [string]: any } }
-- [op]: operator result stored with a register key
Fused.ArithSetR = {} :: { [string]: any }
Fused.ArithKSetR = {} :: { [string]: any }
-- [op]: field load feeding a register-constant operator
Fused.GetArithK = {} :: { [string]: any }
-- [op]: operator result stored into a field
Fused.ArithSet = {} :: { [string]: any }
Fused.ArithKSet = {} :: { [string]: any }
-- [op1 .. "_" .. op2][side]: operator result feeding another operator
Fused.ArithArith = {} :: { [string]: { [string]: any } }
-- [op1 .. "_" .. op2]: operator result feeding a register-constant operator
Fused.ArithArithK = {} :: { [string]: any }
-- [first .. kind]: a value computed for a conditional branch (successors as in Ops/Branches)
Fused.Branch = {} :: { [string]: any }
""")

maker("Fused.GetGet", ["A1: number", "B1: number", "K1: any", "A2: number", "B2: number", "K2: any"],
      ["S[A1] = S[B1][K1]", "S[A2] = S[B2][K2]"], "Two field loads.")
maker("Fused.GetSet", ["A1: number", "B1: number", "K1: any", "B2: number", "K2: any"],
      ["local v = S[B1][K1]", "S[A1] = v", "S[B2][K2] = v"], "Field copy: a load whose result is stored.")
maker("Fused.SetGet", ["A1: number", "B1: number", "K1: any", "A2: number", "B2: number", "K2: any"],
      ["S[B1][K1] = S[A1]", "S[A2] = S[B2][K2]"], "Field store followed by a field load.")

maker("Fused.UpGetK", ["A1: number", "U: number", "A2: number", "K2: any"],
      ["local t = S[1][U]", "S[A1] = t", "S[A2] = t[K2]"], "By-value upvalue indexed with a constant key.")
maker("Fused.UpGet", ["A1: number", "U: number", "A2: number", "C2: number"],
      ["local t = S[1][U]", "S[A1] = t", "S[A2] = t[S[C2]]"], "By-value upvalue indexed with a register key.")

for op, sym in OPS.items():
    emit(f"Fused.GetArith.{op} = {{}}")
    emit(f"Fused.GetRArith.{op} = {{}}")
    maker(f"Fused.GetArith.{op}.L", ["A1: number", "B1: number", "K1: any", "A2: number", "O: number"],
          ["local v = S[B1][K1]", "S[A1] = v", f"S[A2] = v {sym} S[O]"], f"Field load as the left operand of {op}.")
    maker(f"Fused.GetArith.{op}.R", ["A1: number", "B1: number", "K1: any", "A2: number", "O: number"],
          ["local v = S[B1][K1]", "S[A1] = v", f"S[A2] = S[O] {sym} v"], f"Field load as the right operand of {op}.")
    maker(f"Fused.GetArithK.{op}", ["A1: number", "B1: number", "K1: any", "A2: number", "K2: any"],
          ["local v = S[B1][K1]", "S[A1] = v", f"S[A2] = v {sym} K2"], f"Field load feeding {op}K.")
    maker(f"Fused.GetRArith.{op}.L", ["A1: number", "B1: number", "C1: number", "A2: number", "O: number"],
          ["local v = S[B1][S[C1]]", "S[A1] = v", f"S[A2] = v {sym} S[O]"], f"Register-key load as the left operand of {op}.")
    maker(f"Fused.GetRArith.{op}.R", ["A1: number", "B1: number", "C1: number", "A2: number", "O: number"],
          ["local v = S[B1][S[C1]]", "S[A1] = v", f"S[A2] = S[O] {sym} v"], f"Register-key load as the right operand of {op}.")
    maker(f"Fused.ArithSetR.{op}", ["A1: number", "B1: number", "C1: number", "B2: number", "C2: number"],
          [f"local v = S[B1] {sym} S[C1]", "S[A1] = v", "S[B2][S[C2]] = v"], f"{op} stored with a register key.")
    maker(f"Fused.ArithKSetR.{op}", ["A1: number", "B1: number", "K1: any", "B2: number", "C2: number"],
          [f"local v = S[B1] {sym} K1", "S[A1] = v", "S[B2][S[C2]] = v"], f"{op}K stored with a register key.")
    maker(f"Fused.ArithSet.{op}", ["A1: number", "B1: number", "C1: number", "B2: number", "K2: any"],
          [f"local v = S[B1] {sym} S[C1]", "S[A1] = v", "S[B2][K2] = v"], f"{op} stored into a field.")
    maker(f"Fused.ArithKSet.{op}", ["A1: number", "B1: number", "K1: any", "B2: number", "K2: any"],
          [f"local v = S[B1] {sym} K1", "S[A1] = v", "S[B2][K2] = v"], f"{op}K stored into a field.")

for op1, s1 in OPS.items():
    for op2, s2 in OPS.items():
        key = f"{op1}_{op2}"
        emit(f"Fused.ArithArith.{key} = {{}}")
        maker(f"Fused.ArithArith.{key}.L", ["A1: number", "B1: number", "C1: number", "A2: number", "O: number"],
              [f"local v = S[B1] {s1} S[C1]", "S[A1] = v", f"S[A2] = v {s2} S[O]"], f"{op1} as the left operand of {op2}.")
        maker(f"Fused.ArithArith.{key}.R", ["A1: number", "B1: number", "C1: number", "A2: number", "O: number"],
              [f"local v = S[B1] {s1} S[C1]", "S[A1] = v", f"S[A2] = S[O] {s2} v"], f"{op1} as the right operand of {op2}.")
        maker(f"Fused.ArithArithK.{key}", ["A1: number", "B1: number", "C1: number", "A2: number", "K2: any"],
              [f"local v = S[B1] {s1} S[C1]", "S[A1] = v", f"S[A2] = v {s2} K2"], f"{op1} feeding {op2}K.")



def branch_maker(name, params, prelude, cond, doc):
    """Emits a maker for an instruction feeding a conditional branch, in the four chained/returning combinations."""
    emit(f"-- {doc}")
    emit(f"{name} = function({', '.join(params)}, N: Handler, NC: boolean, T: Handler, TC: boolean): Handler")
    combos = [("NC and TC", "T(S)", "N(S)"), ("NC", "T", "N(S)"), ("TC", "T(S)", "N"), (None, "T", "N")]
    for guard, taken, fall in combos:
        indent = "\t\t" if guard else "\t"
        if guard:
            emit(f"\t{'if' if guard == 'NC and TC' else 'elseif'} {guard} then")
        elif True:
            emit("\tend")
        emit(f"{indent}return function(S)")
        for line in prelude:
            emit(f"{indent}\t{line}")
        emit(f"{indent}\tif {cond} then")
        emit(f"{indent}\t\treturn {taken}")
        emit(f"{indent}\tend")
        emit(f"{indent}\treturn {fall}")
        emit(f"{indent}end")
    emit("end")
    emit("")


FIRSTS = {
    "GetK": (["A1: number", "B1: number", "K1: any"], ["local v = S[B1][K1]", "S[A1] = v"], "Constant-key field load"),
    "Get": (["A1: number", "B1: number", "C1: number"], ["local v = S[B1][S[C1]]", "S[A1] = v"], "Register-key table load"),
    "ModK": (["A1: number", "B1: number", "K1: any"], ["local v = S[B1] % K1", "S[A1] = v"], "MODK"),
}
for first, (params, prelude, what) in FIRSTS.items():
    branch_maker(f"Fused.Branch.{first}Truthy", params, prelude, "v", f"{what} feeding JUMPIF.")
    branch_maker(f"Fused.Branch.{first}EqK", params + ["K2: any"], prelude, "v == K2", f"{what} feeding a JUMPXEQK compare.")
    # value dead after the branch: not stored (A1 kept in the signature so makers stay interchangeable)
    bare = prelude[:1]
    branch_maker(f"Fused.Branch.{first}TruthyDead", params, bare, "v", f"{what} feeding JUMPIF; value not kept.")
    branch_maker(f"Fused.Branch.{first}EqKDead", params + ["K2: any"], bare, "v == K2", f"{what} feeding a JUMPXEQK compare; value not kept.")

emit("return Fused")
print("\n".join(out))
